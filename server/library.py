"""The library's reference list and proof-of-work report, for Referee for Mac's Library window.

Uses the same citation styles as the Word helper (citations.py), so a reference reads the same
in Word, the app and the browser extension.
"""

import html
import time
from typing import Dict, List, Optional

import citations


def in_project(item_project: Optional[str], project: Optional[str]) -> bool:

    """
    project None: everything. "": only sources with no project. Otherwise that project only.
    """

    if project is None:
        return True
    if project == "":
        return not item_project
    return item_project == project


def cited_sources(sources: List[Dict], claims: List[Dict], project: Optional[str]) -> List[Dict]:

    """
    Sources that back a claim, in order of first citation (claims arrive oldest first).
    """

    by_url = {s.get("url"): s for s in sources}
    cited: Dict[str, Dict] = {}
    for claim in claims:
        url = (claim.get("source") or {}).get("url")
        if claim.get("label") == "supports" and url and in_project(claim.get("project"), project) and url not in cited:
            cited[url] = by_url.get(url) or claim["source"]
    return list(cited.values())


def references(sources: List[Dict], claims: List[Dict], project: Optional[str], style: str) -> Dict:

    cited = cited_sources(sources, claims, project)
    numbers = {s.get("url"): i + 1 for i, s in enumerate(cited)}
    ordered = cited if style in citations.NUMBERED else sorted(cited, key=citations.sort_key)
    return {
        "heading": citations.HEADINGS.get(style, "References"),
        "entries": [citations.reference(style, s, number=numbers[s.get("url")]) for s in ordered],
    }


def report(sources: List[Dict], claims: List[Dict], project: Optional[str], style: str) -> str:

    """
    A self-contained HTML page: what was read and when, and which claims each source backs.
    """

    name = "All reading" if project is None else project or "No project"
    # "%-d" (day without a leading zero) only works on macOS and Linux, so the day is added separately.
    when = lambda t: f"{time.localtime(t).tm_mday} {time.strftime('%b %Y, %H:%M', time.localtime(t))}" if t else "—"
    read = sorted((s for s in sources if in_project(s.get("project"), project)), key=lambda s: s.get("captured_ts") or 0)
    cited = cited_sources(sources, claims, project)
    numbers = {s.get("url"): i + 1 for i, s in enumerate(cited)}
    by_url = {s.get("url"): s for s in sources}
    supported = [c for c in claims if c.get("label") == "supports" and in_project(c.get("project"), project)]
    e = html.escape

    reading_rows = "".join(
        f"<tr><td>{e(when(s.get('captured_ts')))}</td><td>{e(citations.clean_title(s))}<br><span class='url'>{e(s.get('url') or '')}</span></td></tr>"
        for s in read)
    claim_rows = ""
    for c in supported:
        url = c["source"].get("url")
        source = by_url.get(url) or c["source"]
        cite = citations.in_text(style, source, number=numbers.get(url), page=c.get("page"), time=c.get("time"))
        claim_rows += (f"<tr><td>{e(c['sentence'])}</td><td>{e(cite)}<br><q>{e(c.get('quote') or '')}</q></td>"
                       f"<td>{e(when((by_url.get(url) or {}).get('captured_ts')))}</td><td>{e(when(c.get('at')))}</td></tr>")

    return f"""<!doctype html><html lang="en-GB"><head><meta charset="utf-8">
<title>Proof of work: {e(name)}</title>
<style>
  :root {{ --text: #1f2328; --muted: #6b7280; --line: #e5e7eb; --page: #ffffff; }}
  @media (prefers-color-scheme: dark) {{ :root {{ --text: #e6e6e6; --muted: #9aa0a6; --line: #30363d; --page: #0d1117; }} }}
  @media print {{ :root {{ --text: #1f2328; --muted: #6b7280; --line: #e5e7eb; --page: #ffffff; }} }}
  body {{ font: 14px/1.5 Georgia, serif; color: var(--text); background: var(--page); max-width: 920px; margin: 32px auto; padding: 0 20px; }}
  h1 {{ font-size: 22px; margin-bottom: 4px; }} h2 {{ font-size: 16px; margin-top: 28px; }}
  .meta, .url, .note {{ color: var(--muted); font-size: 12px; }}
  table {{ width: 100%; border-collapse: collapse; margin-top: 8px; }}
  th, td {{ text-align: left; vertical-align: top; padding: 6px 8px; border-bottom: 1px solid var(--line); }}
  th {{ font-size: 12px; text-transform: uppercase; letter-spacing: 0.04em; color: var(--muted); }}
</style></head><body>
<h1>Proof of work: {e(name)}</h1>
<div class="meta">Generated by Referee on {e(when(time.time()))} · {len(read)} source{'' if len(read) == 1 else 's'} read · {len(supported)} supported claim{'' if len(supported) == 1 else 's'}</div>
<h2>Reading log</h2>
{f"<table><tr><th>Read</th><th>Source</th></tr>{reading_rows}</table>" if read else "<p>No reading has been recorded.</p>"}
<h2>Claims and their evidence</h2>
{f"<table><tr><th>Claim</th><th>Source and supporting passage</th><th>Source read</th><th>Claim checked</th></tr>{claim_rows}</table>" if supported else "<p>No supported claims yet.</p>"}
<p class="note">Reading times were recorded by Referee when each source was captured, and claims when Referee checked them
as they were written. Both are kept on this computer. This report shows the research behind the writing; it is not tamper-proof.</p>
<p class="note">To keep a copy, print this page (Cmd+P) and choose "Save as PDF".</p>
</body></html>"""


